<?php

namespace App\Models;

use CodeIgniter\Model;

class ShippingLabelSettingsModel extends Model
{
    protected $table = 'ajobmart_shipping_label_settings';
    protected $primaryKey = 'id';
    protected $returnType = 'array';

    protected $allowedFields = [
        'company_name',
        'logo_path',
        'label_size',
        'show_order_number',
        'show_label_number',
        'show_seller_details',
        'show_product_details',
        'show_payment_details',
        'show_shipment_details',
        'footer_text',
        'updated_by',
    ];

    protected $useTimestamps = true;
    protected $createdField = 'created_at';
    protected $updatedField = 'updated_at';

    /**
     * Get the single global label settings record.
     */
    public function getSettings(): array
    {
        $settings = $this->find(1);

        if ($settings) {
            return $settings;
        }

        $this->insert([
            'id' => 1,
            'company_name' => 'Ajobmart',
            'label_size' => 'A5',
            'show_order_number' => 1,
            'show_label_number' => 1,
            'show_seller_details' => 1,
            'show_product_details' => 1,
            'show_payment_details' => 1,
            'show_shipment_details' => 1,
            'footer_text' => 'Generated by Ajobmart.',
        ]);

        return $this->find(1) ?? [];
    }

    /**
     * Save global label settings.
     */
    public function saveSettings(array $data): bool
    {
        $existing = $this->find(1);

        if ($existing) {
            return $this->update(1, $data);
        }

        $data['id'] = 1;

        return (bool) $this->insert($data);
    }
}
